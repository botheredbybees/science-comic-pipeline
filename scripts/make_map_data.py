#!/usr/bin/env python3
"""Make renderers/xkcd/mapdata.py: simplified outlines of the southern landmasses, for the `map` prop.

    python scripts/make_map_data.py                 # downloads the file below, writes renderers/xkcd/mapdata.py
    python scripts/make_map_data.py land.geojson    # or use a copy you already have

Source: Natural Earth 1:110m "Land" (ne_110m_land), which is in the public domain (naturalearthdata.com). Each polygon that
reaches south of 8 degrees S is cut at that latitude (the rim of the widest map), simplified, and written as lists of
(longitude, latitude). The result is a small table, committed to the repo, so drawing a map needs no download.
"""
import json
import math
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson"
OUT = Path(__file__).resolve().parents[1] / "renderers" / "xkcd" / "mapdata.py"
EDGE = -8.0  # the widest map reaches to 8 degrees S


def clip_south(poly, edge=EDGE):
    """Cut a polygon (list of (lon, lat)) to latitudes <= edge, Sutherland-Hodgman against one parallel."""
    out = []
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        ain, bin_ = a[1] <= edge, b[1] <= edge
        if ain:
            out.append(a)
        if ain != bin_:
            t = (edge - a[1]) / (b[1] - a[1])
            out.append((a[0] + (b[0] - a[0]) * t, edge))
    return out


def project(pt, span):
    """A point on a unit disc, for measuring how far simplification moves it (0 degrees up, east clockwise)."""
    lon, lat = pt
    r = (90 + lat) / span
    a = math.radians(lon)
    return (r * math.sin(a), -r * math.cos(a))


def simplify(pts, tol, span):
    """Douglas-Peucker on the projected points; `tol` is a fraction of the map's radius."""
    P = [project(p, span) for p in pts]

    def dist(p, a, b):
        (x, y), (x1, y1), (x2, y2) = p, a, b
        dx, dy = x2 - x1, y2 - y1
        if dx == dy == 0:
            return math.hypot(x - x1, y - y1)
        t = max(0, min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
        return math.hypot(x - (x1 + t * dx), y - (y1 + t * dy))

    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        worst, k = 0.0, None
        for m in range(i + 1, j):
            d = dist(P[m], P[i], P[j])
            if d > worst:
                worst, k = d, m
        if k is not None and worst > tol:
            keep[k] = True
            stack += [(i, k), (k, j)]
    return [p for p, k in zip(pts, keep) if k]


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    raw = Path(argv[0]).read_text() if argv else urllib.request.urlopen(URL, timeout=60).read().decode()
    data = json.loads(raw)
    shapes = []
    for f in data["features"]:
        g = f["geometry"]
        for rings in ([g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]):
            pts = [(x, y) for x, y in rings[0]]
            if min(y for _, y in pts) < EDGE:
                shapes.append(pts)
    result = {"antarctica": [], "land": []}
    for pts in shapes:
        south = min(y for _, y in pts)
        if south <= -88:  # Antarctica: finer, because the polar map is twice as large (to 50 S)
            clipped = [(x, y) for x, y in pts if y > -89.9]  # drop the line along the pole that closes the data's polygon
            result["antarctica"].append([(round(x, 1), round(y, 1)) for x, y in simplify(clipped, 0.004, 40.0)])
        else:
            clipped = clip_south(pts)
            if len(clipped) >= 3:
                s = simplify(clipped, 0.006, 82.0)
                if len(s) >= 3:
                    result["land"].append([(round(x, 1), round(y, 1)) for x, y in s])
    lines = ['"""Simplified outlines of the southern landmasses for the `map` prop. Generated by scripts/make_map_data.py from',
             'Natural Earth 1:110m land (public domain). Each outline is a list of (longitude, latitude) in degrees."""', ""]
    for key in ("antarctica", "land"):
        lines.append(f"{key.upper()} = [")
        for poly in result[key]:
            lines.append("    " + repr(poly) + ",")
        lines.append("]")
        lines.append("")
    OUT.write_text("\n".join(lines))
    n = sum(len(p) for k in result for p in result[k])
    print(f"wrote {OUT} ({len(result['antarctica'])} Antarctic and {len(result['land'])} other outlines, {n} points, {OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
